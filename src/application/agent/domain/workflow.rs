//! Workflows: a list of steps, each handed to a subagent, written once in
//! TOML and turned into an Agent Skill that tells the main agent how to run
//! them, the same for every harness.

use std::collections::BTreeSet;

use anyhow::{Result, bail};
use serde::Deserialize;

use crate::application::shared::domain::ResourceName;

/// The first line of the body of every skill casulo generates from a
/// workflow, so a skill the user wrote is never mistaken for one and
/// overwritten.
const GENERATED_MARKER: &str = "> Generated by casulo from `workflows/";

/// A validated workflow from `~/.casulo/agent/workflows/<name>.toml`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Workflow {
    /// Name, equal to the file name without `.toml`.
    pub name: ResourceName,
    /// What the workflow does. Never empty.
    pub description: String,
    /// The steps in the order they are written. Never empty.
    pub steps: Vec<Step>,
}

/// One step of a workflow: work handed to one subagent.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Step {
    /// Unique in the workflow; the subagent's name when not set.
    pub id: ResourceName,
    /// The subagent that does the work. It exists.
    pub agent: ResourceName,
    /// What to ask of the subagent, beyond its own instructions.
    pub task: Option<String>,
    /// Whether the main agent stops for the user's approval after it.
    pub approve: bool,
    /// Ids of the steps that must finish first. Each is a step of the
    /// workflow, and they form no cycle.
    pub depends_on: Vec<ResourceName>,
}

/// The file exactly as written in TOML, before validation.
#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
struct RawWorkflow {
    description: String,
    #[serde(default)]
    step: Vec<RawStep>,
}

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
struct RawStep {
    id: Option<String>,
    agent: String,
    task: Option<String>,
    #[serde(default)]
    approve: bool,
    // `None` (left out) means "after the step above"; `Some([])` means "first".
    depends_on: Option<Vec<String>>,
}

impl Workflow {
    /// Parses a workflow file. `file_name` is its name without `.toml`, and
    /// `known_agents` the subagents a step may use.
    pub fn parse(file_name: &str, text: &str, known_agents: &[ResourceName]) -> Result<Self> {
        let name = ResourceName::parse(file_name)?;
        Self::skill_name(&name)?;
        let raw: RawWorkflow = toml::from_str(text)?;
        let description = raw.description.split_whitespace().collect::<Vec<_>>();
        if description.is_empty() {
            bail!("description is empty; say what the workflow does");
        }
        if raw.step.is_empty() {
            bail!("the workflow has no steps; add one with [[step]] and agent = \"<subagent>\"");
        }
        let mut steps: Vec<Step> = Vec::new();
        for raw_step in raw.step {
            let agent = ResourceName::parse(&raw_step.agent)?;
            let id = match &raw_step.id {
                Some(id) => ResourceName::parse(id)?,
                None => agent.clone(),
            };
            if steps.iter().any(|step| step.id == id) {
                bail!(
                    "two steps have the id \"{id}\"; give one of them another id with id = \"...\""
                );
            }
            if !known_agents.contains(&agent) {
                bail!(
                    "step \"{id}\" uses subagent \"{agent}\", which does not exist; create it with `casulo add agent {agent}`"
                );
            }
            let task = match raw_step.task {
                Some(task) if task.trim().is_empty() => {
                    bail!("the task of step \"{id}\" is empty; say what to do, or leave it out")
                }
                task => task.map(|task| task.trim().to_string()),
            };
            let depends_on = match raw_step.depends_on {
                Some(ids) => {
                    let mut parsed: Vec<ResourceName> = Vec::new();
                    for depended in ids {
                        let depended = ResourceName::parse(&depended)?;
                        if !parsed.contains(&depended) {
                            parsed.push(depended);
                        }
                    }
                    parsed
                }
                None => steps
                    .last()
                    .map(|step| step.id.clone())
                    .into_iter()
                    .collect(),
            };
            steps.push(Step {
                id,
                agent,
                task,
                approve: raw_step.approve,
                depends_on,
            });
        }
        for step in &steps {
            for depended in &step.depends_on {
                if !steps.iter().any(|other| &other.id == depended) {
                    bail!(
                        "step \"{}\" depends on \"{depended}\", which is not a step of this workflow",
                        step.id
                    );
                }
            }
        }
        let workflow = Self {
            name,
            description: description.join(" "),
            steps,
        };
        workflow.order()?;
        Ok(workflow)
    }

    /// The name of the skill a workflow is turned into, `workflow-<name>`.
    /// Fails when it would be longer than a skill name may be.
    pub fn skill_name(name: &ResourceName) -> Result<ResourceName> {
        match ResourceName::parse(&format!("workflow-{name}")) {
            Ok(skill) => Ok(skill),
            Err(_) => bail!(
                "the workflow name \"{name}\" is too long: its skill, workflow-{name}, must fit in a skill name; choose a shorter one"
            ),
        }
    }

    /// Whether `text` is a skill casulo generated from a workflow, which
    /// may be replaced, rather than one the user wrote.
    pub fn is_generated_skill(text: &str) -> bool {
        text.lines().any(|line| line.starts_with(GENERATED_MARKER))
    }

    /// The `SKILL.md` that tells the main agent how to run this workflow.
    /// The text is the same for every harness.
    pub fn to_skill(&self) -> String {
        let name = &self.name;
        let order = self
            .order()
            .expect("a parsed workflow has no cycle, so it has an order");
        let description = if self.description.ends_with(['.', '!', '?']) {
            self.description.clone()
        } else {
            format!("{}.", self.description)
        };
        // A folded block (`>`) needs no escaping, whatever the description holds.
        let mut text = format!(
            "---\nname: workflow-{name}\ndescription: >\n  {description} Use when the user asks for the {name} workflow.\n---\n\n"
        );
        text.push_str(&format!(
            "{GENERATED_MARKER}{name}.toml`: change it with `casulo edit workflow {name}`, not here.\n\n"
        ));
        text.push_str(&format!("# Workflow: {name}\n\n{description}\n\n"));
        text.push_str(
            "Run this workflow for the user's request by handing each step below to its \
             subagent with your subagent tool. Do not do a step's work yourself.\n\n\
             - Give each subagent the user's request, the task of its step, and the results \
             of the steps it waits for.\n\
             - Start a step only when every step it waits for has finished. Steps that may \
             run in parallel can be handed out at the same time.\n\
             - A subagent cannot talk to the user. When one returns questions, ask the user \
             and give the answers to the steps that follow.\n\
             - At a step that needs approval, show the user its result and stop. Go on only \
             once they approve; if they ask for changes, run the step again with their \
             feedback.\n\
             - If a step fails, stop and tell the user. Never skip a step.\n\
             - When the last step finishes, summarize for the user what each step returned.\n\n\
             ## Steps\n",
        );
        for (position, &index) in order.iter().enumerate() {
            let step = &self.steps[index];
            text.push_str(&format!(
                "\n### {}. {}\n\n- Subagent: `{}`\n",
                position + 1,
                step.id,
                step.agent
            ));
            match &step.task {
                Some(task) => text.push_str(&format!("- Task: {task}\n")),
                None => text.push_str("- Task: the subagent's own job, for the user's request\n"),
            }
            if step.depends_on.is_empty() {
                text.push_str("- Waits for: nothing; it can start at once\n");
            } else {
                text.push_str(&format!("- Waits for: {}\n", code_list(&step.depends_on)));
            }
            let parallel: Vec<ResourceName> = order
                .iter()
                .map(|&other| &self.steps[other])
                .filter(|other| {
                    other.id != step.id
                        && !self.reaches(&step.id, &other.id)
                        && !self.reaches(&other.id, &step.id)
                })
                .map(|other| other.id.clone())
                .collect();
            if !parallel.is_empty() {
                text.push_str(&format!(
                    "- May run in parallel with: {}\n",
                    code_list(&parallel)
                ));
            }
            if step.approve {
                text.push_str(
                    "- Approval: stop, show the user its result and wait for their approval before going on\n",
                );
            }
        }
        text
    }

    /// Indexes of the steps in an order that respects `depends_on`. Among
    /// the steps that are ready, the one written first goes first, so the
    /// order is stable. Fails with the steps of a cycle.
    fn order(&self) -> Result<Vec<usize>> {
        let mut order: Vec<usize> = Vec::new();
        let mut done: BTreeSet<&ResourceName> = BTreeSet::new();
        while order.len() < self.steps.len() {
            let ready = self.steps.iter().enumerate().find(|(index, step)| {
                !order.contains(index)
                    && step
                        .depends_on
                        .iter()
                        .all(|depended| done.contains(depended))
            });
            let Some((index, step)) = ready else {
                let stuck: Vec<ResourceName> = self
                    .steps
                    .iter()
                    .filter(|step| !done.contains(&step.id))
                    .map(|step| step.id.clone())
                    .collect();
                if let [only] = stuck.as_slice() {
                    bail!("step `{only}` waits for itself; change its depends_on");
                }
                bail!(
                    "steps {} wait for each other in a cycle; change their depends_on",
                    code_list(&stuck)
                );
            };
            order.push(index);
            done.insert(&step.id);
        }
        Ok(order)
    }

    /// Whether step `to` waits, directly or not, for step `from`.
    fn reaches(&self, from: &ResourceName, to: &ResourceName) -> bool {
        let mut pending = vec![to];
        let mut seen: BTreeSet<&ResourceName> = BTreeSet::new();
        while let Some(current) = pending.pop() {
            let Some(step) = self.steps.iter().find(|step| &step.id == current) else {
                continue;
            };
            for depended in &step.depends_on {
                if depended == from {
                    return true;
                }
                if seen.insert(depended) {
                    pending.push(depended);
                }
            }
        }
        false
    }
}

/// `a`, `b` and `c`, each in backticks.
fn code_list(names: &[ResourceName]) -> String {
    let quoted: Vec<String> = names.iter().map(|name| format!("`{name}`")).collect();
    match quoted.as_slice() {
        [] => String::new(),
        [only] => only.clone(),
        [rest @ .., last] => format!("{} and {last}", rest.join(", ")),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::application::shared::domain::resource::check_skill;

    fn agents(names: &[&str]) -> Vec<ResourceName> {
        names
            .iter()
            .map(|name| ResourceName::parse(name).unwrap())
            .collect()
    }

    fn feature_agents() -> Vec<ResourceName> {
        agents(&[
            "analyst",
            "planner",
            "implementer",
            "reviewer",
            "security-auditor",
            "documenter",
        ])
    }

    const FEATURE: &str = r#"
description = "Take a feature from request to a reviewed, documented branch"

[[step]]
agent = "analyst"
approve = true

[[step]]
agent = "planner"
task = "Write the plan in docs/plan-<topic>.md"
approve = true

[[step]]
agent = "implementer"

[[step]]
agent = "reviewer"
depends_on = ["implementer"]

[[step]]
agent = "security-auditor"
depends_on = ["implementer"]

[[step]]
agent = "documenter"
depends_on = ["reviewer", "security-auditor"]
"#;

    fn ids(workflow: &Workflow) -> Vec<String> {
        workflow
            .order()
            .unwrap()
            .into_iter()
            .map(|index| workflow.steps[index].id.to_string())
            .collect()
    }

    #[test]
    fn a_step_without_depends_on_waits_for_the_one_above() {
        let text = "description = \"Linear\"\n[[step]]\nagent = \"planner\"\n[[step]]\nid = \"build\"\nagent = \"implementer\"\ntask = \" Build it \"\n";

        let workflow = Workflow::parse("linear", text, &feature_agents()).unwrap();

        assert!(workflow.steps[0].depends_on.is_empty());
        assert_eq!(workflow.steps[1].id.as_str(), "build");
        assert_eq!(workflow.steps[1].depends_on, agents(&["planner"]));
        assert_eq!(workflow.steps[1].task.as_deref(), Some("Build it"));
        assert_eq!(ids(&workflow), ["planner", "build"]);
    }

    #[test]
    fn steps_after_a_shared_one_may_run_in_parallel() {
        let workflow = Workflow::parse("feature", FEATURE, &feature_agents()).unwrap();
        let skill = workflow.to_skill();

        assert_eq!(
            ids(&workflow),
            [
                "analyst",
                "planner",
                "implementer",
                "reviewer",
                "security-auditor",
                "documenter"
            ]
        );
        assert!(skill.contains("- May run in parallel with: `security-auditor`\n"));
        assert!(skill.contains("- May run in parallel with: `reviewer`\n"));
        assert_eq!(skill.matches("May run in parallel").count(), 2);
    }

    #[test]
    fn order_follows_depends_on_rather_than_the_file() {
        let text = "description = \"d\"\n[[step]]\nagent = \"reviewer\"\ndepends_on = [\"implementer\"]\n[[step]]\nagent = \"implementer\"\ndepends_on = []\n";

        let workflow = Workflow::parse("backwards", text, &feature_agents()).unwrap();

        assert_eq!(ids(&workflow), ["implementer", "reviewer"]);
    }

    #[test]
    fn rejects_invalid_workflows() {
        let invalid = [
            ("description = \"d\"\n", "no steps"),
            (
                "description = \" \"\n[[step]]\nagent = \"planner\"\n",
                "description is empty",
            ),
            (
                "description = \"d\"\ncolor = \"red\"\n[[step]]\nagent = \"planner\"\n",
                "unknown field",
            ),
            (
                "description = \"d\"\n[[step]]\nagent = \"planner\"\nwhen = \"always\"\n",
                "unknown field",
            ),
            (
                "description = \"d\"\n[[step]]\nagent = \"planner\"\n[[step]]\nagent = \"planner\"\n",
                "two steps have the id \"planner\"",
            ),
            (
                "description = \"d\"\n[[step]]\nagent = \"planner\"\ndepends_on = [\"design\"]\n",
                "\"design\", which is not a step",
            ),
            (
                "description = \"d\"\n[[step]]\nagent = \"ghost\"\n",
                "casulo add agent ghost",
            ),
            (
                "description = \"d\"\n[[step]]\nagent = \"planner\"\ntask = \"\"\n",
                "task of step \"planner\" is empty",
            ),
            (
                "description = \"d\"\n[[step]]\nagent = \"planner\"\ndepends_on = [\"reviewer\"]\n[[step]]\nagent = \"reviewer\"\n",
                "steps `planner` and `reviewer` wait for each other in a cycle",
            ),
            (
                "description = \"d\"\n[[step]]\nagent = \"planner\"\ndepends_on = [\"planner\"]\n",
                "step `planner` waits for itself",
            ),
        ];
        for (text, expected) in invalid {
            let error = Workflow::parse("broken", text, &feature_agents()).unwrap_err();
            let message = format!("{error:#}");
            assert!(
                message.contains(expected),
                "{expected:?} not in {message:?}"
            );
        }
    }

    #[test]
    fn rejects_a_name_too_long_for_its_skill() {
        let name = "a".repeat(60);
        let text = "description = \"d\"\n[[step]]\nagent = \"planner\"\n";

        let error = Workflow::parse(&name, text, &feature_agents()).unwrap_err();

        assert!(error.to_string().contains("too long"));
    }

    #[test]
    fn the_skill_is_valid_and_marked_as_generated() {
        let workflow = Workflow::parse("feature", FEATURE, &feature_agents()).unwrap();
        let skill = workflow.to_skill();

        let description =
            check_skill(&Workflow::skill_name(&workflow.name).unwrap(), &skill).unwrap();

        assert!(description.starts_with("Take a feature from request"));
        assert!(Workflow::is_generated_skill(&skill));
        assert!(!Workflow::is_generated_skill(
            "---\nname: workflow-feature\ndescription: mine\n---\n"
        ));
    }

    #[test]
    fn skill_of_the_feature_workflow() {
        let workflow = Workflow::parse("feature", FEATURE, &feature_agents()).unwrap();

        insta::assert_snapshot!(workflow.to_skill());
    }
}
