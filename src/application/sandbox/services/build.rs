//! `casulo build`: generate the Dockerfile for a project and harness, and build it.

use std::fs;

use anyhow::{Context, Result};

use crate::application::agent::domain::Harness;
use crate::application::project::domain::ImageSettings;
use crate::application::project::domain::push::CONTAINER_PUSH_DIR;
use crate::application::sandbox::domain::container::{
    CONTAINER_HOME, CONTAINER_UID, CONTAINER_USER, CONTAINER_WORKSPACE, image_tag,
};
use crate::application::sandbox::ports::Images;
use crate::application::shared::domain::{CasuloHome, ProjectName};

/// Base image: Debian slim with the current Node.js LTS, which the npm-based
/// harnesses need. It is the official Node.js image.
const BASE_IMAGE: &str = "node:24-trixie-slim";

/// The Dockerfile for one harness and project. It depends only on the
/// harness and the project's `[image]` settings, never on anything in the
/// workspace.
pub fn dockerfile(harness: &Harness, image: &ImageSettings) -> String {
    let mut text = format!(
        "# Generated by casulo for the \"{name}\" harness. `casulo build` rewrites this file.\n\
         FROM {BASE_IMAGE}\n\
         \n\
         RUN apt-get update \\\n    \
             && apt-get install --yes --no-install-recommends ca-certificates curl git \\\n    \
             && rm -rf /var/lib/apt/lists/*\n\
         \n\
         # The agent runs as this unprivileged user, never as root.\n\
         RUN userdel --remove node \\\n    \
             && useradd --create-home --home-dir {CONTAINER_HOME} --uid {CONTAINER_UID} --shell /bin/bash {CONTAINER_USER}\n\
         \n\
         # The workspace belongs to the host user, so git must be told to trust it.\n\
         RUN git config --system safe.directory {CONTAINER_WORKSPACE}\n\
         \n\
         # Push settings. casulo run mounts this file only when push is enabled;\n\
         # git ignores a missing include, so pushing is off otherwise.\n\
         RUN git config --system include.path {CONTAINER_PUSH_DIR}/push.gitconfig\n\
         \n\
         # Install the agent.\n",
        name = harness.name,
    );
    for line in &harness.install {
        text.push_str(&format!("RUN {line}\n"));
    }
    if !image.install.is_empty() {
        text.push_str("\n# What this project needs, from [image] in its casulo.toml.\n");
        for line in &image.install {
            text.push_str(&format!("RUN {line}\n"));
        }
    }
    text.push_str(&format!(
        "\nUSER {CONTAINER_USER}\nWORKDIR {CONTAINER_WORKSPACE}\n"
    ));
    text
}

/// Writes the Dockerfile to the project's build directory and builds it.
/// Returns the image tag.
pub fn build_image(
    home: &CasuloHome,
    project: &ProjectName,
    harness: &Harness,
    image: &ImageSettings,
    runtime: &dyn Images,
) -> Result<String> {
    let build_dir = home.build_dir(project, &harness.name);
    fs::create_dir_all(&build_dir)
        .with_context(|| format!("cannot create {}", build_dir.display()))?;
    let dockerfile_path = build_dir.join("Dockerfile");
    fs::write(&dockerfile_path, dockerfile(harness, image))
        .with_context(|| format!("cannot write {}", dockerfile_path.display()))?;
    let tag = image_tag(project, &harness.name);
    runtime.build_image(&dockerfile_path, &build_dir, &tag)?;
    Ok(tag)
}

/// Builds the image for `project` and `harness` only when it does not exist
/// yet, so `casulo run` works without a `casulo build` first. Returns the
/// tag when it built the image, `None` when the image was already there.
pub fn build_image_if_missing(
    home: &CasuloHome,
    project: &ProjectName,
    harness: &Harness,
    image: &ImageSettings,
    runtime: &dyn Images,
) -> Result<Option<String>> {
    if runtime.image_exists(&image_tag(project, &harness.name))? {
        return Ok(None);
    }
    build_image(home, project, harness, image, runtime).map(Some)
}

#[cfg(test)]
mod tests {
    use std::cell::RefCell;
    use std::ffi::OsString;
    use std::path::Path;

    use super::*;
    use crate::application::sandbox::test_support::built_in_harness;

    /// A runtime that knows a fixed list of images and records what it builds.
    #[derive(Default)]
    struct FakeRuntime {
        images: Vec<String>,
        // `RefCell` lets `build_image` record calls through the `&self` the trait gives it.
        built: RefCell<Vec<String>>,
    }

    impl Images for FakeRuntime {
        fn build_image(&self, _dockerfile: &Path, _context_dir: &Path, tag: &str) -> Result<()> {
            self.built.borrow_mut().push(tag.to_string());
            Ok(())
        }
        fn image_exists(&self, tag: &str) -> Result<bool> {
            Ok(self.images.iter().any(|image| image == tag))
        }
    }

    #[test]
    fn dockerfile_for_claude() {
        insta::assert_snapshot!(dockerfile(
            &built_in_harness("claude"),
            &ImageSettings::default()
        ));
    }

    #[test]
    fn dockerfile_for_codex() {
        insta::assert_snapshot!(dockerfile(
            &built_in_harness("codex"),
            &ImageSettings::default()
        ));
    }

    #[test]
    fn dockerfile_ends_as_the_unprivileged_user() {
        let text = dockerfile(&built_in_harness("claude"), &ImageSettings::default());
        let last_user = text.lines().rfind(|line| line.starts_with("USER "));

        assert_eq!(last_user, Some("USER casulo"));
        assert!(text.find("RUN npm install").unwrap() < text.find("USER casulo").unwrap());
    }

    #[test]
    fn project_install_runs_as_root_after_the_agent() {
        let image = ImageSettings {
            install: vec!["apt-get install --yes build-essential".to_string()],
        };

        let text = dockerfile(&built_in_harness("claude"), &image);

        let project_step = text
            .find("RUN apt-get install --yes build-essential")
            .unwrap();
        assert!(text.find("RUN npm install").unwrap() < project_step);
        assert!(project_step < text.find("USER casulo").unwrap());
    }

    #[test]
    fn builds_the_image_when_it_is_missing() {
        let directory = tempfile::tempdir().unwrap();
        let home = CasuloHome::resolve(Some(OsString::from(directory.path())), None).unwrap();
        let project = ProjectName::parse("demo").unwrap();
        let runtime = FakeRuntime::default();

        let built = build_image_if_missing(
            &home,
            &project,
            &built_in_harness("claude"),
            &ImageSettings::default(),
            &runtime,
        )
        .unwrap();

        assert_eq!(built.as_deref(), Some("casulo/demo:claude"));
        assert_eq!(*runtime.built.borrow(), ["casulo/demo:claude"]);
    }

    #[test]
    fn skips_the_build_when_the_image_exists() {
        let directory = tempfile::tempdir().unwrap();
        let home = CasuloHome::resolve(Some(OsString::from(directory.path())), None).unwrap();
        let project = ProjectName::parse("demo").unwrap();
        let runtime = FakeRuntime {
            images: vec!["casulo/demo:claude".to_string()],
            ..FakeRuntime::default()
        };

        let built = build_image_if_missing(
            &home,
            &project,
            &built_in_harness("claude"),
            &ImageSettings::default(),
            &runtime,
        )
        .unwrap();

        assert_eq!(built, None);
        assert!(runtime.built.borrow().is_empty());
    }
}
